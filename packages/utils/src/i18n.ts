export const dictionaries: Record<Language, Record<MessageKey, string>> = { en, fa };

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string;

export function createTranslator(language: Language): Translate {
  const dict = dictionaries[language] ?? en;
  const numberFormat = new Intl.NumberFormat(language === 'fa' ? 'fa-IR' : 'en-US');
  return (key, params) => {
    let text = dict[key] ?? en[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, typeof value === 'number' ? numberFormat.format(value) : String(value));
      }
    }
    return text;
  };
}

/** Localized text for an error thrown through the bridge or network engine. */
export function errorText(t: Translate, err: unknown): string {
  const code = (err as { code?: string })?.code;
  const key = `err.${code}` as MessageKey;
  if (code && key in en) return t(key);
  if (code?.startsWith('HTTP_')) return `${t('err.DOWNLOAD_FAILED')} (HTTP ${code.slice(5)})`;
  const message = err instanceof Error ? err.message.replace(/^Error invoking remote method '[^']+': /, '') : '';
  return message || t('err.UNKNOWN');
}
